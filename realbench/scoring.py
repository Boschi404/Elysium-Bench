"""Objective scoring — execution-based, no self-reported grades.

Every code/math task is graded by running its HIDDEN test suite against the
solver's workspace. The tests are copied into the workspace only at scoring
time, so the solver can never see them. Score = passed/total * 100 — a
continuous gradient that discriminates (gold=100, junk≈0, no ceiling).
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

from .task_loader import RealTask

CONFTEST = '''"""Auto-generated by realbench — makes the workspace importable."""
import sys
from pathlib import Path

_WORKSPACE = str(Path(__file__).resolve().parent.parent)
if _WORKSPACE not in sys.path:
    sys.path.insert(0, _WORKSPACE)
'''


@dataclass
class ScoreResult:
    task_id: str
    score: float = 0.0          # 0-100
    passed: int = 0
    failed: int = 0
    collected: int = 0
    collection_errors: int = 0
    failed_test_names: list[str] = field(default_factory=list)
    output: str = ""
    gap: str = ""               # human-readable explanation when scoring broke


def _parse_failed_names(stdout: str) -> list[str]:
    names = []
    for line in stdout.splitlines():
        m = re.match(r"FAILED\s+(\S+)", line.strip())
        if m:
            names.append(m.group(1))
        m = re.match(r"ERROR\s+(\S+)", line.strip())
        if m:
            names.append(m.group(1))
    return names


def _run_pytest_file(test_file: Path, cwd: Path, timeout: int = 300) -> dict:
    """Run pytest on ONE test file. A missing module only zeroes that file's
    tests instead of aborting the whole suite (pytest collection errors are
    otherwise global)."""
    try:
        result = subprocess.run(
            [sys.executable, "-m", "pytest", str(test_file),
             "-q", "--tb=line", "-p", "no:cacheprovider"],
            capture_output=True, text=True, timeout=timeout, cwd=str(cwd),
        )
        stdout = result.stdout or ""
        # "Interrupted: N errors during collection" = import blew up before
        # ANY test ran. Ordinary test failures (even AssertionError, even
        # non-assertion exceptions reported as "errors") are NOT collection
        # errors and are parsed normally below.
        if "Interrupted" in stdout:
            # collection blew up (e.g. missing module): every test in this
            # file counts as failed — count test functions from source
            n_tests = len(re.findall(r"def\s+test_\w+", test_file.read_text(
                encoding="utf-8", errors="ignore")))
            return {"passed": 0, "failed": max(n_tests, 1),
                    "collected": n_tests, "stdout": stdout,
                    "collection_error": True}
        return {"passed": _sum_int(stdout, r"(\d+)\s+passed"),
                "failed": _sum_int(stdout, r"(\d+)\s+failed") + _sum_int(stdout, r"(\d+)\s+errors?"),
                "collected": _sum_int(stdout, r"(\d+)\s+collected"),
                "stdout": stdout, "collection_error": False}
    except subprocess.TimeoutExpired:
        n_tests = len(re.findall(r"def\s+test_\w+", test_file.read_text(
            encoding="utf-8", errors="ignore")))
        return {"passed": 0, "failed": max(n_tests, 1), "collected": n_tests,
                "stdout": "SCORING TIMEOUT", "collection_error": True}


def _sum_int(stdout: str, pattern: str) -> int:
    return sum(int(g) for g in re.findall(pattern, stdout))


def score_workspace(task: RealTask, workspace: Path) -> ScoreResult:
    """Grade a solver workspace against the task's hidden tests.

    Each hidden test file is run in its own pytest invocation so that a
    missing module (e.g. api.py not implemented) zeroes only that module's
    tests — partial credit per module/file is preserved.
    """
    res = ScoreResult(task_id=task.id)
    tests_dir = task.tests_dir
    if tests_dir is None or not list(tests_dir.rglob("test_*.py")):
        res.gap = "task has no hidden tests"
        return res

    # Copy hidden tests into the workspace at scoring time only.
    hidden = workspace / "_realbench_hidden"
    if hidden.exists():
        shutil.rmtree(hidden)
    hidden.mkdir(parents=True)
    for f in tests_dir.rglob("*"):
        if f.is_file():
            dest = hidden / f.relative_to(tests_dir)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, dest)
    (hidden / "conftest.py").write_text(CONFTEST, encoding="utf-8")

    test_files = sorted(hidden.rglob("test_*.py"))
    chunks: list[str] = []
    for tf in test_files:
        out = _run_pytest_file(tf, cwd=workspace, timeout=task.timeout_seconds)
        res.passed += out["passed"]
        res.failed += out["failed"]
        res.collected += out["collected"]
        res.failed_test_names += _parse_failed_names(out["stdout"])
        chunks.append(out["stdout"][-1500:])
        if out.get("collection_error"):
            res.collection_errors += 1
    res.output = "\n".join(chunks)[-4000:]

    total = res.passed + res.failed
    if total > 0:
        res.score = round(res.passed / total * 100, 1)
    else:
        res.gap = "no tests ran"
    return res


def score_gold(task: RealTask) -> ScoreResult:
    """Calibration: grade the reference solution. Must be 100."""
    gold = task.gold_dir
    if gold is None:
        return ScoreResult(task_id=task.id, gap="no gold dir")
    with tempfile.TemporaryDirectory(prefix="realbench_gold_") as tmp:
        ws = Path(tmp)
        # repo files first (bug hunt), then gold files override
        if task.repo_dir is not None:
            for f in task.repo_dir.iterdir():
                if f.is_file():
                    shutil.copy2(f, ws / f.name)
        for f in gold.iterdir():
            if f.is_file() and not f.name.startswith("gen_"):
                shutil.copy2(f, ws / f.name)
        return score_workspace(task, ws)
